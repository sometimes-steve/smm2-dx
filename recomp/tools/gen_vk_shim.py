"""Windows: the Vulkan loader's entry points as forwarders to vulkan-1.dll, loaded at run time.

Linked against vulkan-1.dll's import library, the exe doesn't start at all on a PC without the loader (no Vulkan
driver, a basic display driver, some VMs and Remote Desktop): Windows stops it before main with "vulkan-1.dll was not
found". With these forwarders in its place the exe starts, finds the loader missing (runtime/platform/windows.c) and
says what to install. Each forwarder looks its function up in vulkan-1.dll on its first call.

    python tools/gen_vk_shim.py <vulkan include dir> <out.c> <source file or folder>...

A forwarder is made for every Vulkan function (vkXxx) the given sources mention, if the Vulkan headers declare it: the
build passes the runtime's own sources and the ImGui Vulkan backend, so nothing is listed by hand.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PROTO = re.compile(r"VKAPI_ATTR\s+([^;{}()]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\)\s*;", re.S)


def arg_name(arg: str) -> str:
    arg = re.sub(r"\[[^\]]*\]", "", arg).strip()
    return re.findall(r"\w+", arg)[-1]


def main() -> int:
    inc, out = Path(sys.argv[1]), Path(sys.argv[2])
    files = []
    for arg in sys.argv[3:]:
        p = Path(arg)
        files += [f for ext in ("*.c", "*.cpp", "*.h") for f in p.rglob(ext)] if p.is_dir() else [p]
    want = set()
    for f in files:
        want |= set(re.findall(r"(?<![A-Za-z0-9_])vk[A-Z]\w*", f.read_text(encoding="utf-8", errors="replace")))
    protos = {}
    for h in ("vulkan_core.h", "vulkan_win32.h"):
        for ret, name, args in PROTO.findall((inc / "vulkan" / h).read_text()):
            protos[name] = (" ".join(ret.split()), " ".join(args.split()))
    lines = [
        "// Generated by tools/gen_vk_shim.py: the Vulkan loader's entry points, looked up in vulkan-1.dll at run time.",
        "#define VK_USE_PLATFORM_WIN32_KHR",
        "#include <windows.h>",
        "#include <stdio.h>",
        "#include <stdlib.h>",
        "#include <vulkan/vulkan.h>",
        "",
        "static HMODULE vk_shim_dll;",
        "int vk_shim_load(void) {  // (1: the loader is there)",
        '    if (!vk_shim_dll) vk_shim_dll = LoadLibraryA("vulkan-1.dll");',
        "    return vk_shim_dll != NULL;",
        "}",
        "static PFN_vkVoidFunction vk_shim_sym(const char *name) {",
        "    PFN_vkVoidFunction f = vk_shim_load() ? (PFN_vkVoidFunction)(void *)GetProcAddress(vk_shim_dll, name) : NULL;",
        '    if (!f) fprintf(stderr, "FATAL: Vulkan: %s is missing (vulkan-1.dll %s)\\n", name, vk_shim_dll ? "too old" : "not found"), fflush(stderr), abort();',
        "    return f;",
        "}",
        "",
    ]
    n = 0
    for name in sorted(want):
        if name not in protos:
            continue
        ret, args = protos[name]
        names = "" if args.strip() == "void" else ", ".join(arg_name(a) for a in args.split(","))
        call = f"p({names})"
        lines += [
            f"VKAPI_ATTR {ret} VKAPI_CALL {name}({args}) {{",
            f"    static PFN_{name} p;",
            f'    if (!p) p = (PFN_{name})vk_shim_sym("{name}");',
            f"    {'' if ret == 'void' else 'return '}{call};",
            "}",
        ]
        n += 1
    out.write_text("\n".join(lines) + "\n")
    print(f"{out}: {n} Vulkan entry points")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
