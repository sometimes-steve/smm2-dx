#!/bin/bash
# usage: tools/package.sh <target> <build dir> <game id> <deps dir>   (make package TARGET=windows-x86_64 does this)
# A player package for windows-x86_64 (a .zip): the runtime with its setup screen, what recompiling the game on the
# player's machine needs, and nothing from the game. On first launch the setup screen (runtime/ui/launcher.cpp) takes
# the player's own dump and keys, checks and extracts it, recompiles the game code (runtime/gamebuild.c: the bundled
# Python runs the generator, the bundled zig compiles it) and runs the game.
#   <game id>-dx-<target>.exe   the runtime
#   <game id>-dx.dll.a          its import library: the game code DLL links against the exe
#   *.dll                       SDL3 + libiconv, shaderc (Vulkan itself comes with the graphics driver)
#   smm2-dx_data/ the runtime exe, the DLLs, the import library, python/ tools/ gamelib-src/ zig/ hactool/ licenses/ THIRD-PARTY.txt (tools/package_lib.sh)
#   README.txt                  what to do (generated by write_readme in package_lib.sh)
# The package is checked for game content (scripts/check_package.py) before it is archived.
set -euo pipefail
cd "$(dirname "$0")/.."
. tools/package_lib.sh
TARGET=$1 B=$2 ID=$3 DEPS=${4:-}
[ "$TARGET" = windows-x86_64 ] || { echo "package.sh: only windows-x86_64 is supported"; exit 1; }
VERSION=${RECOMP_VERSION:-$(git describe --tags --match 'v[0-9]*' 2>/dev/null || echo dev)}
EXE=$B/${ID}-dx-${TARGET}.exe  # (the launcher: it runs the runtime in smm2-dx_data)
RT=$B/smm2-dx_data/${ID}-dx-runtime.exe
[ -f "$RT" ] && [ -f "$EXE" ] || { echo "no $EXE: make TARGET=$TARGET all first"; exit 1; }
NAME="SMM2Recomp-$TARGET"
OUT=dist/$NAME
rm -rf "$OUT" "dist/$NAME.zip"
mkdir -p "$OUT"
cp "$EXE" "$OUT/"
mkdir -p "$OUT/smm2-dx_data"
cp "$RT" "$OUT/smm2-dx_data/"
cp "$B/smm2-dx_data/${ID}-dx.dll.a" "$OUT/smm2-dx_data/"
for d in SDL3.dll libiconv-2.dll libshaderc_shared.dll; do cp "$DEPS/bin/$d" "$OUT/smm2-dx_data/"; done
cp branding/app-icon.ico "$OUT/smm2-dx_data/SMM2Recomp.ico"  # (also in the exe: runtime/platform/windows.rc)
stage_common "$OUT/smm2-dx_data" "$TARGET" x86_64-windows
write_readme "$OUT/README.txt" "$TARGET" "$VERSION"
python3 scripts/check_package.py "$OUT"
(cd dist && zip -qr -9 "$NAME.zip" "$NAME")
ARCHIVE=dist/$NAME.zip
echo "$ARCHIVE: $(du -h "$ARCHIVE" | cut -f1) ($(du -sh "$OUT" | cut -f1) unpacked), $VERSION"
