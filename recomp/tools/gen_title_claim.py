#!/usr/bin/env python3
"""Renders the text of the title screen's corner line and writes it as the BC7 blocks the game's texture is made of.

The title screen's "(c) 2019 Nintendo" is a picture, not text: the texture Title_Claim_00 (384 x 60, BC7 sRGB) of the layout
Play_Title_00. runtime/nvn/texpatch.c swaps it for the blocks this tool writes when the game uploads it (issue #14), so the
game's own files are never touched or shipped.

Usage:  python recomp/tools/gen_title_claim.py [--text "(c) 2026 sometimes_steve"] [--png preview.png]
Output: recomp/runtime/nvn/title_claim.inc (a C array: 96 x 15 blocks of 16 bytes, rows top to bottom)

Needs Pillow (a build does not: the generated file is part of the source). The font is BIZ UDPGothic (SIL OFL), which the
program already ships. White letters with a dark outline, as the original. Encoding: BC7 mode 5 with fixed endpoints (black
and white colour, transparent and opaque alpha) and a 2-bit index for each: 4 levels of grey and 4 of alpha.
"""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
W, H = 384, 60
SS = 4  # supersampling
FONT = ROOT / "recomp" / "games" / "smm2" / "BIZUDPGothic-Regular.ttf"
OUT = ROOT / "recomp" / "runtime" / "nvn" / "title_claim.inc"
LEVELS = [0, (255 * 21 + 32) >> 6, (255 * 43 + 32) >> 6, 255]  # BC7's 2-bit weights 0, 21, 43, 64 between 0 and 255
OUTLINE = 3  # px at 1x


def render(text):
    """RGBA pixels (W x H, tuples): white fill, black outline, centred."""
    size = 60
    while size > 8:
        font = ImageFont.truetype(str(FONT), size * SS)
        box = ImageDraw.Draw(Image.new("L", (1, 1))).textbbox((0, 0), text, font=font, stroke_width=OUTLINE * SS)
        if box[2] - box[0] <= (W - 8) * SS and box[3] - box[1] <= (H - 6) * SS:
            break
        size -= 1
    ox = (W * SS - (box[2] - box[0])) // 2 - box[0]
    oy = (H * SS - (box[3] - box[1])) // 2 - box[1]
    fill = Image.new("L", (W * SS, H * SS), 0)
    edge = Image.new("L", (W * SS, H * SS), 0)
    ImageDraw.Draw(edge).text((ox, oy), text, font=font, fill=255, stroke_width=OUTLINE * SS, stroke_fill=255)
    ImageDraw.Draw(fill).text((ox, oy), text, font=font, fill=255)
    fill = fill.resize((W, H), Image.LANCZOS)
    edge = edge.resize((W, H), Image.LANCZOS)
    fp, ep = fill.load(), edge.load()
    out = []
    for y in range(H):
        row = []
        for x in range(W):
            t, o = fp[x, y] / 255.0, ep[x, y] / 255.0
            a = t + o * (1 - t) * 0.92  # (the outline is a little see-through)
            if a <= 0:
                row.append((0, 0, 0, 0))
                continue
            g = 255 * t / a  # (white over black, un-premultiplied)
            row.append((round(g), round(g), round(g), round(255 * a)))
        out.append(row)
    return out


def nearest(v):
    return min(range(4), key=lambda i: abs(LEVELS[i] - v))


def encode_block(px):
    """BC7 mode 5: RGB 7-bit endpoints, alpha 8-bit endpoints, 2-bit colour and alpha indices (rotation 0)."""
    cidx = [nearest(p[0]) for p in px]  # (grey: R = G = B)
    aidx = [nearest(p[3]) for p in px]
    c0, c1, a0, a1 = 0, 127, 0, 255
    if cidx[0] >= 2:  # (the first index of each set has one bit only: swap the endpoints)
        c0, c1 = c1, c0
        cidx = [3 - i for i in cidx]
    if aidx[0] >= 2:
        a0, a1 = a1, a0
        aidx = [3 - i for i in aidx]
    v, n = 0, 0

    def put(value, bits):
        nonlocal v, n
        v |= value << n
        n += bits

    put(1 << 5, 6)  # mode 5: five zero bits, then a one
    put(0, 2)       # rotation
    for e0, e1 in ((c0, c1),) * 3:  # R0 R1, G0 G1, B0 B1
        put(e0, 7)
        put(e1, 7)
    put(a0, 8)
    put(a1, 8)
    for i, c in enumerate(cidx):
        put(c, 1 if i == 0 else 2)
    for i, a in enumerate(aidx):
        put(a, 1 if i == 0 else 2)
    assert n == 128
    return v.to_bytes(16, "little")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--text", default="© 2026 sometimes_steve")
    ap.add_argument("--png", help="also write a preview of the encoded result")
    args = ap.parse_args()
    img = render(args.text)
    blocks = bytearray()
    for by in range(H // 4):
        for bx in range(W // 4):
            px = [img[by * 4 + i // 4][bx * 4 + i % 4] for i in range(16)]
            blocks += encode_block(px)
    assert len(blocks) == (W // 4) * (H // 4) * 16
    lines = [
        "// Generated by recomp/tools/gen_title_claim.py (do not edit): the title screen's corner line, %r, as the BC7 blocks of"
        % args.text,
        "// the texture it replaces (384 x 60, 96 x 15 blocks, rows top to bottom). Not from the game's files.",
        "static const unsigned char k_title_claim[%d] = {" % len(blocks),
    ]
    for i in range(0, len(blocks), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in blocks[i:i + 24]) + ",")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT} ({len(blocks)} bytes)")
    if args.png:
        flat = Image.new("RGBA", (W, H))
        flat.putdata([p for row in img for p in row])
        bg = Image.new("RGBA", (W, H), (70, 70, 70, 255))
        bg.alpha_composite(flat)
        bg.convert("RGB").save(args.png)


if __name__ == "__main__":
    main()
